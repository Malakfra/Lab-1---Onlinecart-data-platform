def product_price(product):
    """Price actually charged by the app (the app never has the 'JOD' or missing-price problem)."""
    text = product["unit_price"].replace(" JOD", "")
    return float(text) if text else 1.00


def make_order(rng, order_date, sequence, customers, products, corrupt):
    placed_at = datetime.combine(order_date, datetime.min.time()) + timedelta(
        hours=rng.randint(7, 22), minutes=rng.randint(0, 59), seconds=rng.randint(0, 59))
    customer = rng.choice(customers)
    status = rng.choices(STATUSES, weights=STATUS_WEIGHTS)[0]

    items = []
    for product in rng.sample(products, rng.randint(1, 6)):
        quantity = rng.randint(1, 4)
        if rng.random() < 0.005:
            quantity = -rng.randint(1, 2)                          # PROBLEM: negative quantity
        items.append({"product_id": product["product_id"], "quantity": quantity,
                      "unit_price": product_price(product)})
    if rng.random() < 0.002:
        items = []                                                  # PROBLEM: order with no items

    total = round(sum(i["quantity"] * i["unit_price"] for i in items), 2)
    if rng.random() < 0.01:
        total = round(total + rng.choice([1, 2, 5]), 2)             # PROBLEM: total does not match items

    delivered_at = None
    if status == "delivered":
        delivered_at = (placed_at + timedelta(minutes=rng.randint(18, 75))).isoformat()

    shown_status = status
    roll = rng.random()
    if roll < 0.10:
        shown_status = status.capitalize()                          # PROBLEM: "Delivered"
    elif roll < 0.15:
        shown_status = status.upper()                               # PROBLEM: "DELIVERED"

    customer_id = customer["customer_id"]
    if rng.random() < 0.01:
        customer_id = None                                          # PROBLEM: missing customer

    order = {
        "order_id": f"ORD-{order_date:%Y%m%d}-{sequence:05d}",
        "customer_id": customer_id,
        "order_timestamp": placed_at.isoformat(),
        "updated_at": (delivered_at or placed_at.isoformat()),
        "zone": customer["zone"].strip().title() or rng.choice(ZONES),
        "status": shown_status,
        "payment": {"method": rng.choice(PAYMENT_METHODS), "total_amount": total},
        "delivery": {"rider_id": f"R{rng.randint(1, 60):03d}", "delivered_at": delivered_at},
        "items": items,
    }

    if corrupt:                                                     # extra damage for Week 8
        roll = rng.random()
        if roll < 0.15:
            order["customer_id"] = None
        elif roll < 0.20:
            order["status"] = "unknown"
        elif roll < 0.23 and items:
            items[0]["product_id"] = "P999"                         # product that does not exist
        elif roll < 0.26 and items:
            items[0]["unit_price"] = -items[0]["unit_price"]        # negative price
        elif roll < 0.28:
            order["order_timestamp"] = placed_at.strftime("%d/%m/%Y %H:%M")  # different date format
    return order


def make_duplicate(rng, order):
    """PROBLEM: the app sometimes exports an order twice - an older and a newer version."""
    older = json.loads(json.dumps(order))                           # an independent copy
    older["status"] = "out_for_delivery"
    older["delivery"]["delivered_at"] = None
    older["updated_at"] = (datetime.fromisoformat(order["order_timestamp"])
                           + timedelta(minutes=rng.randint(5, 15))).isoformat()
    return older


def make_orders_for_day(seed, export_date, customers, products, corrupt=False):
    rng = random.Random(f"{seed}-{export_date.isoformat()}-{'corrupt' if corrupt else 'normal'}")
    orders = [make_order(rng, export_date, n, customers, products, corrupt)
              for n in range(1, rng.randint(*ORDERS_PER_DAY) + 1)]

    duplicates = [make_duplicate(rng, o) for o in rng.sample(orders, max(1, len(orders) // 50))
                  if o["status"].lower() == "delivered" and "/" not in o["order_timestamp"]]
    orders.extend(duplicates)

    if export_date == LATE_ORDER_FILE_DATE:                          # late-arriving orders
        late_date = export_date - timedelta(days=LATE_ORDER_DAYS_BACK)
        late_rng = random.Random(f"{seed}-late")
        for n in range(1, 4):
            orders.append(make_order(late_rng, late_date, 90000 + n, customers, products, False))

    if export_date >= SCHEMA_CHANGE_DATE:                            # schema change
        for order in orders:
            order["delivery_fee"] = rng.choice([0.0, 0.5, 1.0])

    rng.shuffle(orders)                                              # files are not sorted
    return {
        "export_id": f"EXP-{export_date:%Y%m%d}{'-C' if corrupt else ''}",
        "export_date": export_date.isoformat(),
        "generated_at": f"{export_date.isoformat()}T23:59:00",
        "source_system": "quickcart-mobile-app",
        "record_count": len(orders),
        "orders": orders,
    }


# ----------------------------------------------------------------------------------------------
# Writing the files
# ----------------------------------------------------------------------------------------------
def write_csv(path, rows):
    with open(path, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def main():
    parser = argparse.ArgumentParser(description="Generate QuickCart source exports.")
    parser.add_argument("--seed", type=int, required=True,
                        help="last 4 digits of your student ID")
    parser.add_argument("--date", help="generate ONE day, e.g. 2026-10-04")
    parser.add_argument("--start", default="2026-10-01", help="first day of a range")
    parser.add_argument("--days", type=int, default=3, help="number of days in the range")
    parser.add_argument("--corrupt", action="store_true", help="add extra data problems")
    args = parser.parse_args()

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    customers = make_customers(args.seed)
    products = make_products(args.seed)
    write_csv(OUTPUT_DIR / "customers.csv", customers)
    write_csv(OUTPUT_DIR / "products.csv", products)
    print(f"Wrote customers.csv ({len(customers)} rows) and products.csv ({len(products)} rows)")

    if args.date:
        days = [date.fromisoformat(args.date)]
    else:
        first = date.fromisoformat(args.start)
        days = [first + timedelta(days=i) for i in range(args.days)]

    for day in days:
        export = make_orders_for_day(args.seed, day, customers, products, args.corrupt)
        path = OUTPUT_DIR / f"orders_{day.isoformat()}.json"
        with open(path, "w", encoding="utf-8") as f:
            json.dump(export, f, indent=2)
        print(f"Wrote {path.name} ({export['record_count']} order records)")

    print(f"Done. Files are in: {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
