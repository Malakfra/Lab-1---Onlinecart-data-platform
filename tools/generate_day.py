def make_phone(rng):
    """Return a Jordanian-style mobile number in one of three DIFFERENT formats (a data problem)."""
    digits = f"7{rng.choice('789')}{rng.randint(1000000, 9999999)}"
    style = rng.random()
    if style < 0.6:
        return f"0{digits}"                                   # 07XXXXXXXX
    if style < 0.85:
        return f"+962 {digits[:2]} {digits[2:5]} {digits[5:]}"  # +962 7X XXX XXXX
    return f"962-{digits[:2]}-{digits[2:]}"                   # 962-7X-XXXXXXX


def make_customers(seed):
    rng = random.Random(f"{seed}-customers")
    customers = []
    for number in range(1, NUMBER_OF_CUSTOMERS + 1):
        first = rng.choice(FIRST_NAMES)
        last = rng.choice(LAST_NAMES)
        zone = rng.choice(ZONES)
        roll = rng.random()
        if roll < 0.02:
            zone = ""                                  # PROBLEM: missing zone
        elif roll < 0.05:
            zone = zone.lower() + " "                  # PROBLEM: inconsistent text ("khalda ")
        signup = date(2024, 1, 1) + timedelta(days=rng.randint(0, 900))
        customers.append({
            "customer_id": f"C{number:04d}",
            "first_name": first,
            "last_name": last,
            "email": f"{first}.{last}{number}@example.com".lower(),
            "phone": make_phone(rng),
            "zone": zone,
            "signup_date": signup.isoformat(),
        })
    # PROBLEM: the same people registered twice (new id, same e-mail written in capitals)
    for original in rng.sample(customers, 3):
        copy = dict(original)
        copy["customer_id"] = f"C{len(customers) + 1:04d}"
        copy["email"] = original["email"].upper()
        customers.append(copy)
    return customers


def make_products(seed):
    rng = random.Random(f"{seed}-products")
    products = []
    for number, (name, category, price, supplier) in enumerate(PRODUCT_CATALOGUE, start=1):
        price = round(price * rng.uniform(0.9, 1.1), 2)        # each student gets slightly different prices
        products.append({
            "product_id": f"P{number:03d}",
            "product_name": name,
            "category": category,
            "unit_price": f"{price:.2f}",
            "supplier": supplier,
        })
    products[rng.randrange(len(products))]["unit_price"] = ""                    # PROBLEM: missing price
    victim = products[rng.randrange(len(products))]
    victim["unit_price"] = f"{victim['unit_price']} JOD"                         # PROBLEM: text in a number column
    for product in rng.sample(products, 2):
        product["category"] = product["category"].lower()                       # PROBLEM: "dairy" vs "Dairy"
    return products


